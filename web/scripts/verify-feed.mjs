import {chromium} from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce',serviceWorkers:'block'});
await context.addInitScript(()=>localStorage.setItem('bne.preferences.v2',JSON.stringify({'check-domains':false,count:'4000'})));
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4173/brand-name-explorer/');
await page.waitForFunction(()=>document.querySelector('#results').dataset.count==='4000');
assert.ok(await page.locator('#results .name-card').count()<=300);
await page.locator('#next').click();
await page.waitForFunction(()=>document.querySelector('#results').dataset.count==='8000');
await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(200);
const initial=await page.locator('#results .name-card').first().getAttribute('data-domain');
await page.locator('#results .save-name').nth(99).focus();await page.keyboard.press('Tab');
assert.equal(await page.evaluate(()=>document.activeElement.closest('.name-card').getAttribute('aria-posinset')),'101');
await page.keyboard.press('Shift+Tab');
assert.equal(await page.evaluate(()=>document.activeElement.closest('.name-card').getAttribute('aria-posinset')),'100');
await page.evaluate(()=>{document.activeElement.blur();scrollTo(0,document.body.scrollHeight-1000);});await page.waitForTimeout(300);
assert.ok(await page.locator('#results .name-card').count()<=300);
assert.ok(await page.locator('#results .name-card[aria-posinset="8000"]').count());
await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(300);
assert.equal(await page.locator('#results .name-card').first().getAttribute('data-domain'),initial);
const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze();
assert.deepEqual(axe.violations,[]);
await page.locator('#tune-btn').click();await page.locator('#advanced-controls').evaluate(e=>e.open=true);
const downloaded=page.waitForEvent('download');await page.locator('#export-results').click();const download=await downloaded;
const csv=await readFile(await download.path(),'utf8');assert.equal(csv.trim().split('\n').length,8001);
assert.equal(new Set(csv.trim().split('\n').slice(1).map(l=>l.split(',')[0])).size,8000);
assert.deepEqual(errors,[]);
console.log(JSON.stringify({logicalRows:8000,renderedRows:await page.locator('#results .name-card').count(),keyboardAcrossBlocks:true,scrollBackRetainsNames:true,csvRows:8000,axe:0,errors}));
await browser.close();
